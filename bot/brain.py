_REL_NUM = {"один": 1, "одну": 1, "два": 2, "две": 2, "три": 3, "четыре": 4, "пять": 5, "шесть": 6, "пол": 0.5}


def _relative_dt(text):
    """«через 2 часа», «через два часа», «через час», «через полчаса», «через 30 минут» → дата-время (МСК)."""
    t = (text or "").lower()
