_DATE_WORD_RE = re.compile(r"послезавтра|завтра|сегодня|\b\d{1,2}[./]\d{1,2}(?:[./]\d{2,4})?\b|\b\d{1,2}\s+(?:январ|феврал|"
                           r"март|апрел|ма[яй]|июн|июл|август|сентябр|октябр|ноябр|декабр)\w*", re.I)


def _latest_date(user_msgs):
    """Последняя дата, которую назвал клиент: «сегодня» → «ладно, завтра» → «завтра». Пусто, если не называл."""
    for m in reversed(user_msgs):
        found = [x.group(0) for x in _DATE_WORD_RE.finditer(m or "")
                 # «в 09.00», «к 14.30» — это время, а не дата
                 if not (re.match(r"\d{1,2}[.]\d{2}$", x.group(0))
                         and (re.search(r"(?:\bв|\bк|\bс|\bдо|\bна)\s*$", (m or "")[:x.start()], re.I)
                              or int(x.group(0).split(".")[1]) > 12))]
        if found:
            return found[-1].lower()
    return ""


def _latest_time(user_msgs):
    """Последнее время, которое назвал клиент: «в 09:00» → «ладно в 12:00» → «12:00». Пусто, если не называл."""
    for m in reversed(user_msgs):
        rel = _relative_dt(m)
        if rel:
            return f"{rel:%H:%M}"
        if re.search(r"\d{5,}", re.sub(r"[\s()+-]", "", m or "")) and not re.search(r"\b\d{1,2}[:.]\d{2}\b", m or ""):
            continue                               # сообщение с телефоном
        found = re.findall(r"\b([01]?\d|2[0-3])[:.]([0-5]\d)\b", m or "")
        found = [f for f in found if not re.search(rf"\b{f[0]}\.{f[1]}\b(?!\s*(?:утра|вечера|ч))", m) or
                 re.search(rf"(?:\bв|\bк|\bс|\bдо)\s*{f[0]}\.{f[1]}", m, re.I)]   # «08.03» — дата, не время
        if found:
            h, mm = found[-1]
            return f"{int(h):02d}:{mm}"
        h = _hour_from_text(m)
        if h is not None and re.search(r"\b(?:в|к|на|до|около)\s*\d", m or "", re.I):
            return f"{h:02d}:00"
    return ""


