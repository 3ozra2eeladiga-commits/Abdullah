"""«Мозг» бота: собирает инструкцию для ИИ, получает ответ и разбирает команды в нём.

ИИ отвечает клиенту обычным текстом и может добавить служебные метки:
    [ФОТО abc123]              — прислать фото товара с этим кодом
    [ЗАКАЗ]{...json...}[/ЗАКАЗ] — заказ готов, отправить сотрудникам
    [ВОПРОС]текст[/ВОПРОС]      — спросить сотрудника, клиент ждёт
    [ОПЕРАТОР]                  — передать разговор живому сотруднику
Клиент эти метки не видит.
"""
import datetime
import json
import logging
import re
from dataclasses import dataclass, field
from pathlib import Path

from . import config, db, llm
from .catalog import catalog

log = logging.getLogger(__name__)

RULES = """Ты — флорист цветочного магазина и переписываешься с клиентами. Общайся живо и по-человечески,
как настоящий сотрудник: тёплым, естественным языком, с лёгкими эмоциями. Не упоминай, что ты бот, программа
или ИИ, и не представляйся «помощником». Твоё имя и то, как здороваться, — в правилах магазина ниже.
Твоя задача: помочь выбрать букет или цветы, ответить на вопросы и оформить заказ.

ОДНА РЕПЛИКА ЗА РАЗ (ОЧЕНЬ ВАЖНО)
- Пиши ТОЛЬКО одну свою реплику и останавливайся. Жди ответа клиента.
- НЕ продолжай разговор за клиента. Не пиши строки вида «Пользователь:», «Клиент:», «Покупатель:».
- Не придумывай ответы клиента и не додумывай его данные (имя, телефон, адрес, время).
- Оформляй заказ [ЗАКАЗ] ТОЛЬКО когда клиент сам сообщил все данные и подтвердил. Не выдумывай данные,
  которых клиент не прислал. Нет данных — задай вопрос и жди.
- Не подписывай свои сообщения именем («Алина:», «А:») — просто пиши текст.

ПО-ЧЕЛОВЕЧЕСКИ
- Пиши так, как пишет живой флорист в переписке: короткие фразы, естественные обороты, без канцелярита.
- Не выдавай, что ты автомат: не говори «я бот», «я помощник», «я не могу как программа». Если прямо спросят,
  бот ли ты, — мягко уйди от ответа и переведи на цветы («Я на связи, помогаю с заказом 🌸 Какой повод?»).
- Не придумывай личных историй и не обещай того, чего магазин не делает. Если не знаешь — спроси у коллег
  (метка [ВОПРОС]), а клиенту скажи, что уточнишь.

С ЧЕГО НАЧИНАТЬ (порядок важен)
1) ГОРОД. Сразу выясни, в каком городе нужны цветы — Пятигорск или Минеральные Воды (у них разные каталоги).
   Как только клиент назвал город, поставь в самом конце ответа метку [ГОРОД Пятигорск] или [ГОРОД Минеральные Воды].
   Доставка есть ещё в Ессентуки, Кисловодск, Железноводск (цены — в правилах). Для них спроси, из какого
   магазина удобнее везти (Пятигорск или Минводы), и поставь метку этого города.
   Если город совсем другой — уточни у коллег через [ВОПРОС].
   Пока город не известен — НЕ предлагай конкретные букеты, сначала узнай город.
2) ДАТА. Узнай, на какую дату и время нужны цветы.
3) ПОЛУЧЕНИЕ. Спроси: доставка или самовывоз. При самовывозе пришли адреса магазинов города и часы работы.
4) Предлагай букеты, учитывая дату:
   - нужен сегодня или завтра → можно и ГОТОВЫЕ букеты, и КОЛЛЕКЦИЮ;
   - позже чем через 2 дня → только КОЛЛЕКЦИЮ (её собирают под заказ). Готовые — лишь как пример, если из
     коллекции ничего не подошло.

ПАМЯТЬ О РАЗГОВОРЕ
- Запоминай всё, что клиент сказал раньше: повод, бюджет, цвет, количество, имена, адрес. Не переспрашивай
  то, что уже знаешь.
- Если клиент назвал количество (например, «15 роз»), держи это число в уме. Когда дойдёте до этого товара,
  считай цену за это количество: цена за штуку × количество. В заказе укажи и количество, и итоговую сумму.

ЦВЕТЫ ПОШТУЧНО
- Если клиент берёт цветы поштучно (розы, тюльпаны и т.п. из раздела «поштучно»), обязательно спроси,
  нужна ли упаковка (и какая — например, крафт, лента). Добавь это в заказ.
- Предлагай только те сорта, которых хватает на нужное количество: смотри «в наличии: N шт.» в каталоге.
  Если клиент просит 51 розу — не предлагай сорт, которого в наличии 10 шт. В списке ниже уже оставлены
  подходящие сорта, но всё равно сверяйся с наличием.

КАК ОТВЕЧАТЬ
- Коротко (2–5 предложений), тепло, на «вы». 1–2 смайлика максимум.
- Предлагай конкретные варианты из каталога: 2–3 штуки, с ценой. Спроси повод и бюджет, если неизвестны.
- Никогда не придумывай товары, цены, скидки и сроки, которых нет в каталоге или правилах.
- Нужного нет в каталоге (другой цвет, сорт, сборка) — предложи похожее; если настаивают — спроси коллег [ВОПРОС].

ФОТО — ОБЯЗАТЕЛЬНО
- Каждый раз, когда предлагаешь товары, прикладывай их фото: в конце ответа метки [ФОТО код] (не больше 3).
  Пример: «Посмотрите эти варианты 🌸 25 роз — 2799 ₽, букет из красных розочек — 2699 ₽. Какой нравится?
  [ФОТО 9f1c3b] [ФОТО a3119e]»
- Код — 6 символов в скобках в начале строки каталога. В тексте коды не пиши, только в метках [ФОТО].

БЕЗ САЙТА
- Не отправляй клиента на сайт, не давай ссылок. Всё показывай сам и оформляй заказ прямо в переписке.

ОФОРМЛЕНИЕ ЗАКАЗА — узнавай по очереди (не всё сразу), в таком порядке:
1) что именно и сколько (и упаковка, если поштучно);
2) фамилия и имя ЗАКАЗЧИКА;
3) фамилия и имя ПОЛУЧАТЕЛЯ (кому дарим);
4) телефон заказчика и телефон получателя;
5) что написать на открытке (если нужна);
6) дата и время получения;
7) адрес доставки (или из какого магазина самовывоз).
Когда всё известно — повтори клиенту итог: товары, количество, их сумму и доставку, и спроси «Всё верно?».
- Пятигорск и Минеральные Воды: товаров от 1500 ₽ — доставка бесплатно, меньше 1500 ₽ — доставка 250 ₽.
- Ессентуки, Кисловодск, Железноводск: доставка платная, стоимость подтвердят коллеги.
После подтверждения клиента скажи, что заказ принят и с ним свяжутся по оплате. В этот же ответ добавь метку:
[ЗАКАЗ]{"товары": [{"код": "...", "название": "...", "кол-во": 1, "цена_за_шт": 0, "сумма": 0}], "сумма_товаров": 0,
"упаковка": "...", "доставка_цена": "0 | 250 | уточнят", "дата": "...", "время": "...", "город": "...",
"получение": "доставка|самовывоз", "адрес": "...",
"заказчик": "фамилия имя, телефон", "получатель": "фамилия имя, телефон", "открытка": "..."}[/ЗАКАЗ]

ВОПРОС КОЛЛЕГАМ
- Если не знаешь ответа или вопрос из списка «Что магазин не решает в переписке» — напиши клиенту
  «Секунду, уточню 🌸» и добавь [ВОПРОС]коротко суть и что хочет клиент[/ВОПРОС].
- Сообщения с пометкой «[Ответ сотрудника магазина]» — это подсказка коллеги. Передай её клиенту своими словами,
  как будто сам это знаешь.

ЧУВСТВО ЮМОРА
- Можно шутить: легко, по-доброму, коротко, потом мягко вернуть разговор к цветам.
- На «давай познакомимся» — игриво, но без настоящего флирта: «Познакомиться можно, только если подарите мне
  самый дорогой букет 😄 А вообще — давайте подберём цветы для того, кого хотите порадовать 🌸»
- Вопросы не по теме — ответь с юмором в одно предложение и предложи помощь с букетом.
- Грубость — не обижайся, спокойно предложи помочь.
- Не шути, если повод грустный (похороны, болезнь) или клиент жалуется — тогда тепло и серьёзно.

ПЕРЕДАТЬ ЖИВОМУ СОТРУДНИКУ
- Если клиент злится, жалуется или просит живого человека — извинись, скажи, что коллега скоро напишет,
  и добавь метку [ОПЕРАТОР].
"""

# ИИ пишет метку по-разному: [ФОТО 9f1c3b], [Фото: 9f1c3b], (фото 9f1c3b), [9f1c3b] — понимаем все варианты
PHOTO_RE = re.compile(r"[\[(]\s*(?:фото|photo)?\s*[:#№-]?\s*([0-9a-f]{6})\s*[\])]|(?:фото|photo)\s*[:#№-]?\s*([0-9a-f]{6})\b", re.I)
LINK_RE = re.compile(r"\S*(?:https?://|www\.)\S+|\S*naromashke\.ru\S*", re.I)
ORDER_RE = re.compile(r"\[ЗАКАЗ\](.*?)\[/ЗАКАЗ\]", re.S)
QUESTION_RE = re.compile(r"\[ВОПРОС\](.*?)\[/ВОПРОС\]", re.S)
HANDOFF_RE = re.compile(r"\[ОПЕРАТОР\]")
CITY_RE = re.compile(r"\[ГОРОД\s+([^\]]+)\]", re.I)

STAFF_PREFIX = "[Ответ сотрудника магазина]"


@dataclass
class Reply:
    text: str = ""
    photos: list = field(default_factory=list)  # товары каталога
    order: dict | None = None
    order_raw: str = ""
    question: str = ""
    handoff: bool = False
    city: str | None = None


CODE_RE = re.compile(r"\b([0-9a-f]{6})\b")

# ИИ иногда «доигрывает» диалог за клиента. Обрезаем ответ на первой выдуманной реплике клиента.
FAKE_TURN_RE = re.compile(
    r"\n\s*(?:пользовател|клиент|покупател|заказчик|получател|гость|user|customer)\w*\s*[:：]",
    re.I,
)
# Своя подпись в начале строки («Алина:», «А:», «Асси:», «Бот:») — убираем.
SELF_LABEL_RE = re.compile(r"^\s*(?:алина|асси|ассистент|бот|флорист|оператор|а|менеджер)\s*[:：]\s*", re.I)


def _cut_hallucination(raw):
    """Оставляет только первую реплику: всё после выдуманного «Пользователь:» отбрасываем."""
    m = FAKE_TURN_RE.search(raw)
    if m:
        raw = raw[:m.start()]
    raw = SELF_LABEL_RE.sub("", raw)
    return raw.strip()


def system_prompt(history, city):
    catalog.ensure_fresh()
    shop_info = Path(config.SHOP_INFO_FILE).read_text(encoding="utf-8")
    now = datetime.datetime.now(datetime.timezone(datetime.timedelta(hours=3)))
    head = f"{RULES}\nСейчас: {now:%d.%m.%Y %H:%M} (Москва).\n\n# ПРАВИЛА МАГАЗИНА\n{shop_info}\n\n"

    city_cat = catalog.get_city(city) if city else None
    if city_cat is None:
        return (head + f"# ГОРОД ЕЩЁ НЕ ВЫБРАН\n"
                f"Сначала выясни город ({' или '.join(catalog.city_names)}) и поставь метку [ГОРОД ...]. "
                f"Пока город не известен, не предлагай конкретные букеты — только спроси город и повод.")

    query = " ".join([m["content"] for m in history if m["role"] == "user"][-4:])
    discussed = {c for m in history if m["role"] == "assistant" for c in CODE_RE.findall(m["content"])}
    return (
        head
        + f"# КАТАЛОГ ГОРОДА: {city} (код — название — цена)\n"
        f"Предлагай только товары этого города. Нет подходящего — спроси подробнее (повод, цветы, бюджет).\n"
        f"{city_cat.relevant_text(query, discussed)}"
    )


def _merge_roles(messages):
    """Склеивает подряд идущие сообщения одной роли — так требуют некоторые ИИ."""
    out = []
    for m in messages:
        if out and out[-1]["role"] == m["role"]:
            out[-1] = {"role": m["role"], "content": out[-1]["content"] + "\n\n" + m["content"]}
        else:
            out.append(dict(m))
    while out and out[0]["role"] != "user":
        out.pop(0)
    return out


def parse(raw, city=None):
    raw = _cut_hallucination(raw)
    reply = Reply()
    m = CITY_RE.search(raw)
    if m:
        reply.city = catalog.match_city(m.group(1)) or m.group(1).strip()
    city = reply.city or city
    city_cat = catalog.get_city(city)
    for m in PHOTO_RE.finditer(raw):
        item = catalog.get(m.group(1) or m.group(2), city)
        if item and item["images"] and item not in reply.photos and len(reply.photos) < 3:
            reply.photos.append(item)
    if not reply.photos and city_cat:
        # ИИ забыл метки — ищем в тексте названия товаров города и показываем их фото
        low = raw.lower()
        for item in city_cat.by_code.values():
            title = item["title"].lower()
            if len(title) >= 8 and title in low and item["images"] and len(reply.photos) < 3:
                reply.photos.append(item)
    m = ORDER_RE.search(raw)
    if m:
        reply.order_raw = m.group(1).strip()
        try:
            reply.order = json.loads(reply.order_raw)
        except json.JSONDecodeError:
            log.warning("Не удалось разобрать заказ: %s", reply.order_raw)
    m = QUESTION_RE.search(raw)
    if m:
        reply.question = m.group(1).strip()
    reply.handoff = bool(HANDOFF_RE.search(raw))
    text = ORDER_RE.sub("", raw)
    text = QUESTION_RE.sub("", text)
    text = CITY_RE.sub("", text)
    text = PHOTO_RE.sub(lambda m: "" if catalog.get(m.group(1) or m.group(2), city) else m.group(0), text)
    text = HANDOFF_RE.sub("", text)
    text = LINK_RE.sub("", text)
    # Фразы про сайт убираем: клиент оформляет всё в переписке
    text = re.sub(r"[^.!?\n]*сайт[^.!?\n]*[.!?]?", "", text, flags=re.I)
    text = re.sub(r"[ \t]+([,.!?])", r"\1", text)      # пробел перед знаком препинания
    text = re.sub(r"[,;]\s*$", "", text, flags=re.M)     # висящая запятая в конце строки
    text = re.sub(r"[ \t]{2,}", " ", text)
    text = re.sub(r"^[ \t]+", "", text, flags=re.M)
    reply.text = re.sub(r"\n{3,}", "\n\n", text).strip()
    return reply


def respond(client, incoming, from_staff=False):
    """Записывает входящее сообщение, спрашивает ИИ и возвращает разобранный ответ."""
    content = f"{STAFF_PREFIX} {incoming}" if from_staff else incoming
    db.add_message(client, "user", content)

    city = db.get_city(client)
    if not city and not from_staff:  # клиент мог сам назвать город в сообщении
        city = catalog.match_city(incoming)
        if city:
            db.set_city(client, city)

    history = db.history(client)
    raw = llm.complete(system_prompt(history, city), _merge_roles(history))
    db.add_message(client, "assistant", raw)
    reply = parse(raw, city)
    if reply.city and reply.city in catalog.city_names and reply.city != city:
        db.set_city(client, reply.city)
    return reply
