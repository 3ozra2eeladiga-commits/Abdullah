def _phone_was_given(order_value, client_text):
    """Телефон из заказа должен реально встречаться в сообщениях клиента (а не быть выдуман ИИ)."""
    digits = _phone_digits(order_value)
    if len(digits) < 7:
        return False
    client_digits = _phone_digits(client_text)
    # последние 7 цифр номера должны присутствовать в том, что писал клиент
    return digits[-7:] in client_digits


