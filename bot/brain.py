def _fill_order(order, city):
    """Подставляет в заказ реальные названия и цены товаров по коду из каталога и считает сумму."""
    if not isinstance(order, dict) or not isinstance(order.get("товары"), list):
        return order
    for it in order["товары"]:
        code = (it.get("код") or "").strip().lower()
        real = catalog.get(code, city) if code else None
        if real:
            it["название"] = real["title"]
            it["цена_за_шт"] = real["price"]
            qty = it.get("кол-во") or 1
            it["сумма"] = real["price"] * qty if isinstance(qty, (int, float)) else real["price"]
    try:
        extra = int(order.get("доплата") or 0)
    except (TypeError, ValueError):
        extra = 0
    order["доплата"] = extra
    try:
        order["сумма_товаров"] = sum(int(x.get("сумма") or 0) for x in order["товары"]) + extra
    except (TypeError, ValueError):
        pass
    if not _meaningful(order.get("город")) and city:
        order["город"] = city                    # город клиента известен — иначе доставка вышла бы «уточнят»
    if order.get("адрес"):                       # «подъезд —, этаж —» — заглушки ИИ клиенту не показываем
        a = re.sub(r",?\s*(?:подъезд|под\.|этаж|эт\.|кв\.?|квартира)\s*[—–-]+\s*(?=,|$)", "", str(order["адрес"]), flags=re.I)
        order["адрес"] = a.strip(" ,")
    order["доставка_цена"] = _delivery_price(order)
    return order


def _apply_client_state(order, client, city):
    """Подставляет в заказ то, что клиент уже выбрал, даже если ИИ это забыл: дополнения (открытка и т.п.)
    и доплату «собрать пышнее/скромнее». Пересчитывает суммы."""
    if not isinstance(order, dict):
        return order
    items = order.get("товары")
    if not isinstance(items, list):
        items = order["товары"] = []
    _drop_prev_items(order, client)
    items = order["товары"]
    photo_item = db.get_setting(f"photo_item:{client}")
    if photo_item and not any(not CARD_RE.search(str(it.get("название") or "")) and (it.get("код") or it.get("название"))
                              for it in items if isinstance(it, dict)):
        items.insert(0, {"название": photo_item, "кол-во": 1, "сумма": 0})   # букет по фото клиента
    have = {str(it.get("код") or "").strip().lower() for it in items}
    for code in [c for c in (db.get_setting(f"addons:{client}") or "").split(",") if c]:
        if code not in have and catalog.get(code, city):
            items.append({"код": code, "кол-во": 1})
    for k, v in _draft(client).items():         # чего нет в заказе, но клиент уже говорил — из черновика
        if k in DRAFT_KEYS and not _meaningful(order.get(k)) and _meaningful(v):
            order[k] = v
    if db.get_setting(f"nocard:{client}") and not db.get_setting(f"cardtext:{client}"):
        order["открытка"] = "нет"               # клиент сказал «без открытки» — это окончательно
    ct = db.get_setting(f"cardtext:{client}")
    if ct:
        order["открытка"] = ct              # текст, который клиент подтвердил — как есть, без правок
    up = db.get_setting(f"upsize:{client}") or ""
    if up:
        _code, sign, amount = (up.split("|") + ["", "", ""])[:3]
        if amount:
            order["доплата"] = int(amount) * (-1 if sign == "-" else 1)
            note = (f"Собрать пышнее: добавить цветов на {amount} ₽" if sign != "-"
                    else f"Собрать скромнее: на {amount} ₽ меньше")
            c = str(order.get("комментарий") or "").strip()
            if note not in c:
                order["комментарий"] = (c + "; " if c else "") + note
    return _fill_order(order, city)


_SENT_SPLIT_RE = re.compile(r"(?<=[.!?…])\s+(?=[«\"(]?[А-ЯЁA-Z0-9])|(?<=[\U0001F300-\U0001FAFF\u2600-\u27BF])\s+(?=[А-ЯЁ])")
_ABBR_RE = re.compile(r"(?:\b(?:ул|д|кв|г|пр|пер|т\.?е|т|стр|корп|эт|под|тел|руб|им)\.|№\s*\d+\.)$", re.I)


def pretty(text):
    """Длинный ответ клиенту одним сплошным абзацем трудно читать — разбиваем на короткие абзацы
    (по 1–2 предложения, вопрос — отдельной строкой). Уже оформленный текст (с переносами) не трогаем."""
    t = (text or "").strip()
    if "\n" in t or len(t) < 140:
        return t
    parts, buf = [], ""
    for piece in _SENT_SPLIT_RE.split(t):
        buf = f"{buf} {piece}".strip() if buf else piece
        if _ABBR_RE.search(buf):
            continue                         # «ул. Крайнего» — не конец предложения
        parts.append(buf)
        buf = ""
    if buf:
        parts.append(buf)
    paras, cur = [], ""
    for i, sent in enumerate(parts):
        last_q = i == len(parts) - 1 and sent.rstrip().endswith("?")
        if cur and (last_q or len(cur) + len(sent) > 160 or cur.count(". ") + cur.count("! ") >= 1):
            paras.append(cur)
            cur = sent
        else:
            cur = f"{cur} {sent}".strip()
    if cur:
        paras.append(cur)
    return "\n\n".join(paras)


