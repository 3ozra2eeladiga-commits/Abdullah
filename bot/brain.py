def _merge_roles(messages):
    """Склеивает подряд идущие сообщения одной роли — так требуют некоторые ИИ."""
    out = []
    for m in messages:
        if out and out[-1]["role"] == m["role"]:
            out[-1] = {"role": m["role"], "content": out[-1]["content"] + "\n\n" + m["content"]}
        else:
            out.append(dict(m))
    while out and out[0]["role"] != "user":
        out.pop(0)
    return out


def parse(raw, city=None):
    raw = _cut_hallucination(raw)
    reply = Reply()
    m = CITY_RE.search(raw)
    if m:
        reply.city = catalog.match_city(m.group(1)) or m.group(1).strip()
    city = reply.city or city
    city_cat = catalog.get_city(city)
    for m in PHOTO_RE.finditer(raw):
        item = catalog.get(m.group(1) or m.group(2), city)
        if item and item["images"] and item not in reply.photos and len(reply.photos) < 10:
            reply.photos.append(item)
    if not reply.photos and city_cat:
        # ИИ забыл метки — ищем в тексте названия товаров города и показываем их фото
        low = raw.lower()
        for item in city_cat.by_code.values():
            title = item["title"].lower()
            if len(title) >= 8 and title in low and item["images"] and len(reply.photos) < 10:
                reply.photos.append(item)
    m = ORDER_RE.search(raw)
    if m:
        reply.order_raw = m.group(1).strip()
        reply.order = _parse_order_json(reply.order_raw)
    else:
        # ИИ вывалил JSON заказа прямо в текст (без пары меток [ЗАКАЗ]…[/ЗАКАЗ]) — забираем его и прячем от клиента.
        span = _order_json_span(raw)
        if span:
            reply.order_raw = raw[span[0]:span[1]]
            reply.order = _parse_order_json(reply.order_raw)
            raw = raw[:span[0]] + raw[span[1]:]
    m = QUESTION_RE.search(raw)
    if m:
        reply.question = m.group(1).strip()
    reply.handoff = bool(HANDOFF_RE.search(raw))
    text = ORDER_RE.sub("", raw)
    text = re.sub(r"\[/?\s*ЗАКАЗ\s*\]", "", text)  # одиночная метка [ЗАКАЗ] без пары — не показываем клиенту
    text = QUESTION_RE.sub("", text)
    text = re.sub(r"\[/?\s*ВОПРОС\s*\]", "", text)  # одиночная метка [ВОПРОС] без пары — не показываем клиенту
    text = CITY_RE.sub("", text)
    text = PHOTO_RE.sub(lambda m: "" if catalog.get(m.group(1) or m.group(2), city) else m.group(0), text)
    # Выдуманные ИИ метки фото ([ФОТО e9876g] с несуществующим кодом) клиенту не показываем.
    text = re.sub(r"\[\s*(?:фото|photo)\b[^\]]*\]", "", text, flags=re.I)
    text = re.sub(r"<(https?://[^>\s]+)>", r"\1", text)          # «<https://сайт>» → «https://сайт»
    text = re.sub(r"[ \t]+([.,:!?])", r"\1", text)
    text = HANDOFF_RE.sub("", text)
    text = FOREIGN_LINK_RE.sub("", text)  # чужие ссылки убираем, а ссылку на наш каталог оставляем
    text = re.sub(r"[ \t]+([,.!?])", r"\1", text)      # пробел перед знаком препинания
    text = re.sub(r"[,;]\s*$", "", text, flags=re.M)     # висящая запятая в конце строки
    text = re.sub(r"[ \t]{2,}", " ", text)
    text = re.sub(r"^[ \t]+", "", text, flags=re.M)
    text = re.sub(r"\n{3,}", "\n\n", text).strip()
    # Бот любит сыпать 🌸 в каждое предложение — оставляем максимум один на сообщение
    if text.count("🌸") > 1:
        first = text.index("🌸")
        text = text[:first + 1] + text[first + 1:].replace("🌸", "")
        text = re.sub(r"[ \t]{2,}", " ", text).strip()
    reply.text = text
    return reply


def respond(client, incoming, from_staff=False, quote=""):
    """Записывает входящее сообщение, спрашивает ИИ и возвращает разобранный ответ.

    quote — текст сообщения, на которое клиент ответил (reply): подпись фото букета и т.п. Используется
    ТОЛЬКО для распознавания (какой букет), но НЕ подмешивается в сам текст для ИИ, чтобы его не путать."""
    if not from_staff:
        incoming = _fix_time_answer(client, _fix_way_typos(client, _fix_common_typos(incoming)),
                                    db.get_setting(f"lastq:{client}") or "")    # «саморезов» → «самовывоз», «дастафка» → «доставка»
    content = f"{STAFF_PREFIX} {incoming}" if from_staff else incoming

    # Ответ на фото со словами «есть ещё варианты / другие» — это НЕ выбор этого товара, а просьба показать другие.
    quote_more = ""
    if quote and MORE_RE.search(incoming or "") and not re.search(
            r"\bэт(?:от|у|о|а)\b|беру|возьм|хочу\s+(?:эт|так)", incoming or "", re.I):
        quote_more, quote = quote, ""
    # Для распознавания букета/города учитываем и цитату (на что ответил клиент).
    detect = f"{incoming}\n{quote}" if quote else incoming

    city = db.get_city(client)
    city_new = False                 # город стал известен именно сейчас — сразу покажем букеты
    if not city and not from_staff:  # клиент мог сам назвать город или прийти по ссылке с сайта города
        city = catalog.match_city(incoming) or _city_from_url(detect)
        # Ответ цифрой на «В какой город? 1 — Пятигорск, 2 — …»
        m_num = re.fullmatch(r"\W*(\d)\W*", incoming or "")
        if not city and m_num and re.search(r"1 — ", _last_bot_text(client, "")) \
                and 1 <= int(m_num.group(1)) <= len(catalog.city_names):
            city = list(catalog.city_names)[int(m_num.group(1)) - 1]
        if city:
            db.set_city(client, city)
            city_new = True

    # Вопрос о недостающем (открытка и т.п.), который в прошлый раз задал КОД вместо ответа ИИ.
    last_q = "" if from_staff else (db.get_setting(f"lastq:{client}") or "")
    if last_q:
        db.del_setting(f"lastq:{client}")
    # Букет, выбранный клиентом: по номеру (№600), ссылке с сайта или ответу (reply) на фото букета.
    picked = ((_picked_by_number(detect, city) + _picked_from_site(detect, city)
               + _picked_from_caption(detect, city)
               + (_picked_card_by_name(incoming, city) if _card_pick_turn(client, incoming, last_q) else [])
               + _card_yes(client, incoming, city, last_q)
               + _picked_by_ordinal(client, incoming, city)
               + _picked_by_price(client, incoming, city))
              if not from_staff else [])
    _seen = set()
    picked = [p for p in picked if not (p["code"] in _seen or _seen.add(p["code"]))]
    # Дополнения (открытка, шар, игрушка…) ДОБАВЛЯЮТ к заказу — выбранный букет при этом не меняется.
    addons = [p for p in picked if catalog.is_addon(p, city)]
    picked = [p for p in picked if p not in addons]
    if picked and not from_staff:
        db.set_setting(f"chosen:{client}", picked[0]["code"])   # букет выбран — других больше не подсовываем
    if addons and not from_staff:
        saved = [c for c in (db.get_setting(f"addons:{client}") or "").split(",") if c]
        # Новая открытка заменяет прежнюю открытку (конверт — прежний конверт), а не добавляется второй.
        def _kind(code):
            it = catalog.get(code)
            m = CARD_RE.search(it["title"]) if it else None
            return m.group(0).lower() if m else None
        new_kinds = {_kind(a["code"]) for a in addons} - {None}
        saved = [c for c in saved if _kind(c) not in new_kinds]
        saved += [a["code"] for a in addons if a["code"] not in saved]
        db.set_setting(f"addons:{client}", ",".join(saved))
    # «Нет» на вопрос про открытку = открытка не нужна (а не «хочу что-то изменить»).
    no_card = (not from_staff and not addons and bool(NO_CARD_RE.search(incoming or ""))
               and bool(re.search(r"открытк", _last_bot_text(client, last_q), re.I)))
    if no_card:
        db.set_setting(f"nocard:{client}", "1")
        content = f"{incoming} — открытка не нужна"
    if addons and any(CARD_RE.search(a["title"]) for a in addons):
        db.del_setting(f"nocard:{client}")
    # В историю пишем слова клиента; если он ответил (reply) на фото — дописываем, о каком товаре речь,
    # обычной фразой. Иначе ИИ видит только «вот это» и переспрашивает номер, хотя всё уже понятно.
    if ((quote and (picked or addons)) or (addons and not picked)) and not from_staff:
        it0 = (picked or addons)[0]
        content = f"{incoming} — про «{it0['title']}» ({it0['price']} ₽)"
    db.add_message(client, "user", content)
    # Клиент выбрал открытку (ответом на фото / названием) — сразу просим текст для неё (или показываем уже
    # названный текст на подтверждение). Не зависим от того, собрал ли ИИ заказ.
    card_pick = next((a for a in addons if CARD_RE.search(a["title"])), None) if not from_staff else None
    if card_pick and not picked and not db.get_setting(f"addto:{client}") and not db.get_setting(f"cardtext:{client}"):
        db.del_setting(f"nocard:{client}")
        wtxt = (db.get_setting(f"wantcard_text:{client}") or "").strip()
        if wtxt:
            q = CARD_TEXT_CONFIRM_Q.format(text=wtxt)
            db.set_setting(f"cardstep:{client}", "confirm:" + wtxt)
        else:
            q = _card_text_q(card_pick["title"])
            db.set_setting(f"cardstep:{client}", "ask")
        text = f"Добавила открытку — {card_pick['price']} ₽ 🌸\n{q}"
        db.set_setting(f"lastq:{client}", q)
        db.add_message(client, "assistant", text)
        return Reply(text=text, city=city)
    # Клиент сам сказал «нужна открытка» (хоть в первом сообщении) — запоминаем, чтобы потом не спрашивать
    # «открытку добавим?», а сразу предложить выбрать. Текст для неё, если назвал, — тоже.
