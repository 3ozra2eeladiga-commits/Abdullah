# Своя подпись в начале строки («Алина:», «А:», «Асси:», «Бот:») — убираем.
SELF_LABEL_RE = re.compile(r"^\s*(?:алина|асси|ассистент|бот|флорист|оператор|а|менеджер)\s*[:：]\s*", re.I)


def _cut_hallucination(raw):
    """Оставляет только первую реплику: всё после выдуманного «Пользователь:» отбрасываем."""
    m = FAKE_TURN_RE.search(raw)
    if m:
        raw = raw[:m.start()]
    raw = SELF_LABEL_RE.sub("", raw)
    return raw.strip()


def system_prompt(history, city):
    catalog.ensure_fresh()
    shop_info = Path(config.SHOP_INFO_FILE).read_text(encoding="utf-8")
    now = datetime.datetime.now(datetime.timezone(datetime.timedelta(hours=3)))
    head = f"{RULES}\nСейчас: {now:%d.%m.%Y %H:%M} (Москва).\n\n# ПРАВИЛА МАГАЗИНА\n{shop_info}\n\n"

    city_cat = catalog.get_city(city) if city else None
    if city_cat is None:
        return (head + f"# ГОРОД ЕЩЁ НЕ ВЫБРАН\n"
                f"Магазины и каталоги есть только в двух городах: {' и '.join(catalog.city_names)}. "
                f"Если клиент назвал один из них — поставь метку [ГОРОД <город>]. "
                f"Если назвал другой город КМВ (Ессентуки, Кисловодск, Железноводск, Иноземцево, Лермонтов и т.п.) — "
                f"не отказывай: выбери ближайший магазин и поставь его метку [ГОРОД ...], а при сомнении коротко "
                f"спроси, из какого магазина удобнее везти. Пока магазин не выбран, не предлагай конкретные букеты.")

    query = " ".join([m["content"] for m in history if m["role"] == "user"][-4:])
    discussed = {c for m in history if m["role"] == "assistant" for c in CODE_RE.findall(m["content"])}
    site = config.cities().get(city, "")
    return (
        head
        + (f"# Ссылка на каталог ({city}): {site}\n\n" if site else "")
        + f"# КАТАЛОГ ГОРОДА: {city} (код — название — цена)\n"
        f"Предлагай только товары этого города. Нет подходящего — спроси подробнее (повод, цветы, бюджет).\n"
        f"{city_cat.relevant_text(query, discussed)}"
    )


def _merge_roles(messages):
    """Склеивает подряд идущие сообщения одной роли — так требуют некоторые ИИ."""
    out = []
    for m in messages:
        if out and out[-1]["role"] == m["role"]:
            out[-1] = {"role": m["role"], "content": out[-1]["content"] + "\n\n" + m["content"]}
        else:
            out.append(dict(m))
    while out and out[0]["role"] != "user":
        out.pop(0)
    return out


