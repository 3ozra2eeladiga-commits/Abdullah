    # Букет уже выбран — других букетов не показываем, пока клиент сам не попросит («покажите другие»).
    chosen = "" if from_staff else (db.get_setting(f"chosen:{client}") or "")
    # ИИ переспрашивает то, что клиент УЖЕ сказал (доставка/дата/время) — заменяем на вопрос о недостающем.
    if not chosen and not from_staff and not order_text and not keep_photos and not reply.order and reply.text \
            and not reply.photos:
        # До выбора букета: ИИ переспрашивает уже сказанные доставку/дату — убираем этот вопрос из ответа.
        um = [m["content"] for m in history if m["role"] == "user"]
        known0 = _known_order(client)
        kw = _KNOWN_Q[0][1](known0, um, client)    # доставка/самовывоз действительно уже известны
        kd = _KNOWN_Q[1][1](known0, um, client)    # и дата со временем
        parts = re.split(r"(?<=[.?!])\s+", reply.text.strip())
        keep = [p for p in parts if not ((kw and re.search(r"доставк\w*\s+или\s+самовывоз|самовывоз\s+или|нужна\s+ли\s+доставк|"
                                                            r"доставка\s+нужна|заед\w*[^.?!]{0,40}магазин", p, re.I))
                                         or (kd and re.search(r"на\s+как\w+\s+(?:дату|день|число)|во\s+сколько|"
                                                              r"к\s+какому\s+(?:часу|времени)|какое\s+время|какая\s+дата",
                                                              p, re.I)))]
        if len(keep) != len(parts):
            if any("?" in p for p in keep):
                reply.text = " ".join(keep).strip()
            elif city and catalog.get_city(city):
                # Переспрашивать нечего — не «какой повод и бюджет?» по кругу, а сразу варианты.
                bud = next((catalog_budget(m) for m in reversed(um) if catalog_budget(m)), None)
                opts = catalog.get_city(city).relevant_items(_catalog_query(history), limit=MIN_OPTIONS * 2,
                                                             bouquets_only=True)
                opts = [p for p in opts if not bud or p["price"] <= bud * 1.1][:MIN_OPTIONS] or opts[:MIN_OPTIONS]
                reply.photos = opts
                reply.text = f"Вот варианты{f' до {bud} ₽' if bud else ''} 🌸 Какой нравится? Ответьте «этот» на фото."
                if not db.get_setting(f"site_sent:{client}") and config.cities().get(city):
                    reply.text += f"\nВсе букеты на сайте: {config.cities()[city]}"
                    db.set_setting(f"site_sent:{client}", "1")
                db.set_setting(f"shown:{client}", ",".join(p["code"] for p in opts))
            else:
                reply.text = ((" ".join(keep).strip() + " ") if keep else "") + "В какой город нужны цветы?"
    if chosen and not order_text and not keep_photos and not reply.order and reply.text:
        user_msgs = [m["content"] for m in history if m["role"] == "user"]
        t = " ".join(user_msgs).lower()
        asks_way = re.search(r"доставк\w*\s+или\s+самовывоз|самовывоз\s+или\s+доставк|заед\w*[^.?!]{0,40}магазин|"
                             r"нужна\s+ли\s+доставк|доставка\s+нужна", reply.text, re.I)
        asks_when = re.search(r"на\s+как\w+\s+(?:дату|день|число)|во\s+сколько|к\s+какому\s+(?:часу|времени)|"
                              r"какое\s+время|какая\s+дата", reply.text, re.I)
        asks_addr = re.search(r"адрес", reply.text, re.I) and "?" in reply.text or re.search(
            r"(?:нужен|уточните|подскажите)[^.?!]{0,30}адрес", reply.text, re.I)
        nxt = _next_question(user_msgs, city, _known_order(client))
        known_way = not re.search(r"доставка или самовывоз", nxt)
        known_when = not re.search(r"дату", nxt)
        # ИИ снова просит имена/телефоны, хотя клиент уже прислал оба номера — не переспрашиваем, идём дальше кодом.
        asks_who = re.search(r"(?:ваш\w*|получател\w*)[^.?!]{0,40}(?:имя|фамили|телефон|номер)|"
                             r"(?:имя|фамили|телефон|номер)[^.?!]{0,40}(?:получател|заказчик|ваш)", reply.text, re.I)
        asks_card = re.search(r"открытк", reply.text, re.I) and "?" in reply.text \
            and not SUMMARY_RE.search(reply.text) and (
            db.get_setting(f"nocard:{client}") or db.get_setting(f"cardtext:{client}")
            or (db.get_setting(f"wantcard:{client}")      # сам просил открытку, а ИИ спрашивает «нужна ли»
                and re.search(r"нужн\w*\s+ли[^.?!]{0,20}открытк|открытк\w*[^.?!]{0,20}(?:нужн|добав|хотите)", reply.text, re.I)))
        reask = ((asks_who and len(PHONE_RE.findall(t)) >= 2) or asks_card
                 or (asks_addr and _has_address(user_msgs) and not (asks_way and not known_way)
                     and not (asks_when and not known_when))
                 or (asks_way and known_way) or (asks_when and known_when))
        if reask:
            # ИИ переспрашивает уже известное. Его ОТВЕТ клиенту (на вопрос «а розы свежие?») оставляем,
            # выкидываем только переспросы — и дальше ведём оформление кодом (итог или недостающее).
            answer = " ".join(p for p in _SENT_SPLIT_RE.split(reply.text.strip())
                              if p and "?" not in p and not REASK_RE.search(p)) if "?" in (incoming or "") else ""
            if picked:
                reply.text = f"Отличный выбор 🌸 {nxt}"
            else:
                advance("Спасибо 🌸 ")
                if answer:
                    reply.text = f"{answer}\n\n{reply.text.replace('Спасибо 🌸 ', '', 1)}"
    if chosen and reply.photos and not keep_photos and not re.search(
            r"друг|ещ[её]|вариант|покаж|покаж|скин|кинь|кидай|поменя|замен|не нрав|передумал", incoming or "", re.I):
        reply.photos = [p for p in reply.photos if p["code"] == chosen and p in picked]
    elif chosen and reply.photos and not keep_photos:
        db.del_setting(f"chosen:{client}")    # клиент сам попросил другие — снимаем «замок»
    # Заказ ещё на проверке у флориста — ИИ не должен сам объявлять его принятым/подтверждённым.
    if not from_staff and not reply.order and db.get_setting(f"ocheck:{client}") and re.search(
            r"заказ\w*\s+(?:уже\s+)?(?:принят|подтвержд|оформлен)", reply.text or "", re.I):
        reply.text = "Заказ на проверке у флориста — скоро напишу 🌸"
    if card_remind and not reply.order:
        reply.photos = []
        reply.text = (reply.text or "").rstrip() + "\n\nКакой текст напишем на открытке?"
    # Новый заказ после оформленного — уже купленный букет среди вариантов не показываем.
    if new_order and reply.photos:
        bought = {p["code"] for p in json.loads(db.get_setting(f"prev_items:{client}") or "[]")}
        reply.photos = [p for p in reply.photos if p["code"] not in bought] or reply.photos
    # Первый показ букетов — сразу и ссылка на сайт магазина этого города: пусть выбирает, как удобно.
    site = config.cities().get(city, "") if city else ""
    if not from_staff and site and len(reply.photos) >= 2 and not keep_photos \
            and not db.get_setting(f"site_sent:{client}") and site not in (reply.text or ""):
        reply.text = ((reply.text or "").rstrip() + f"\nВсе букеты на сайте: {site}").strip()
        db.set_setting(f"site_sent:{client}", "1")
    # Запоминаем, что показали (по порядку) — чтобы понять «давайте последний / второй вариант».
    if not from_staff and (len(reply.photos) >= 2 or (keep_photos and reply.photos)):
        db.set_setting(f"shown:{client}", ",".join(p["code"] for p in reply.photos))
    # ФИНАЛЬНЫЙ ФИЛЬТР ответа ИИ: без «воды», коротко, и никаких вопросов о том, что клиент уже сказал.
    if not from_staff and reply.text and reply.text == ai_text and not reply.order:
        reply.text, to_summary = _polish_ai_text(reply.text, client, city,
                                                 [m["content"] for m in history if m["role"] == "user"])
        if to_summary and not keep_photos:
            advance()                                # всё собрано — показываем итог (или спрашиваем недостающее)
    return reply
