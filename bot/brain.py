def _order_json_span(text):
    """Находит в тексте блок {...} с данными заказа (есть «товары» или «заказчик»). Возвращает (начало, конец)."""
    for i, ch in enumerate(text or ""):
        if ch != "{":
            continue
        depth = 0
        for j in range(i, len(text)):
            if text[j] == "{":
                depth += 1
            elif text[j] == "}":
                depth -= 1
                if depth == 0:
                    block = text[i:j + 1]
                    if '"товары"' in block or '"заказчик"' in block:
                        return i, j + 1
                    break
    return None


def _delivery_price(order):
    """Цена доставки по правилам магазина из shop.json (а не «на глаз» ИИ): по городам магазина — бесплатно
    от free_from ₽, иначе price ₽; другие города — уточнят; самовывоз — 0."""
    if (order.get("получение") or "").lower().startswith("самовывоз"):
        return "0"
    if config.DELIVERY_BY_FLORIST:
        return "уточнят"                       # цену доставки называет флорист при подтверждении
    town = " " + (order.get("город") or "").lower()
    own = any(c.get("name", "").lower() in town or any(a.lower() in town for a in c.get("aliases", []))
              for c in config.city_list())
    if own:
        try:
            total = int(order.get("сумма_товаров") or 0)
        except (TypeError, ValueError):
            total = 0
        return "0" if total >= config.FREE_DELIVERY_FROM else str(config.DELIVERY_PRICE)
    return "уточнят"


