def _order_json_span(text):
    """Находит в тексте блок {...} с данными заказа (есть «товары» или «заказчик»). Возвращает (начало, конец)."""
    for i, ch in enumerate(text or ""):
        if ch != "{":
            continue
        depth = 0
        for j in range(i, len(text)):
            if text[j] == "{":
                depth += 1
            elif text[j] == "}":
                depth -= 1
                if depth == 0:
                    block = text[i:j + 1]
                    if '"товары"' in block or '"заказчик"' in block:
                        return i, j + 1
                    break
    return None


def _delivery_price(order):
    """Цена доставки по правилам магазина из shop.json (а не «на глаз» ИИ): по городам магазина — бесплатно
    от free_from ₽, иначе price ₽; другие города — уточнят; самовывоз — 0."""
    if (order.get("получение") or "").lower().startswith("самовывоз"):
        return "0"
    town = " " + (order.get("город") or "").lower()
    own = any(c.get("name", "").lower() in town or any(a.lower() in town for a in c.get("aliases", []))
              for c in config.city_list())
    if own:
        try:
            total = int(order.get("сумма_товаров") or 0)
        except (TypeError, ValueError):
            total = 0
        return "0" if total >= config.FREE_DELIVERY_FROM else str(config.DELIVERY_PRICE)
    return "уточнят"


def _rub(n):
    return f"{int(n):,}".replace(",", " ") + " ₽"


def _order_summary(o):
    """Короткий итог заказа для клиента — как написал бы живой флорист. Телефоны и служебное — только флористу."""
    items = []
    for it in o.get("товары") or []:
        name = str(it.get("название") or "").strip()
        qty = it.get("кол-во") or 1
        try:
            q = f" × {qty}" if int(qty) > 1 else ""
        except (TypeError, ValueError):
            q = ""
        items.append(f"{name}{q}")
    try:
        extra = int(o.get("доплата") or 0)
    except (TypeError, ValueError):
        extra = 0
    if extra:
        items.append(f"{'собрать пышнее: +' if extra > 0 else 'собрать скромнее: −'}{_rub(abs(extra))}")
    price = str(o.get("доставка_цена") or "")
    when = " ".join(x for x in (str(o.get("дата") or "").strip(), f"к {o['время']}" if o.get("время") else "") if x)
    if (o.get("получение") or "").lower().startswith("самовывоз"):
        how = f"Самовывоз {when}, {o.get('адрес') or ''}".strip(", ")
    else:
        cost = "бесплатно" if price == "0" else (_rub(price) if price.isdigit() else "стоимость уточнит менеджер")
        how = f"Доставка {when}, {o.get('адрес') or ''} — {cost}".strip()
    who = str(o.get("получатель") or "").split(",")[0].strip()
    card = str(o.get("открытка") or "").strip()
    extra = []
    if who:
        extra.append(f"получатель — {who}")
    if card and card.lower() not in ("нет", "не нужна", "-", "—"):
        extra.append(f"открытка «{card}»")
    lines = ["Отлично, всё записала 🌸", ", ".join(items), how]
    if extra:
        t = ", ".join(extra)
        lines.append(t[:1].upper() + t[1:])
    try:
        total = int(o.get("сумма_товаров") or 0) + (int(price) if price.isdigit() else 0)
        lines.append(f"Итого: {_rub(total)}" + ("" if price.isdigit() else " + доставка"))
    except (TypeError, ValueError):
        pass
    lines.append("Всё верно?")
    return "\n".join(lines)


def _parse_order_json(s):
    """Разбирает JSON заказа, терпимо к типичным огрехам ИИ (лишние запятые, текст вокруг)."""
    for candidate in (s, s[s.find("{"): s.rfind("}") + 1] if "{" in s and "}" in s else s):
        try:
            return json.loads(candidate)
        except json.JSONDecodeError:
            pass
    s = re.sub(r'(["\d\]}])\s*\n(\s*["{])', r"\1,\n\2", s)  # ИИ забыл запятые между строками
    fixed = re.sub(r",\s*([}\]])", r"\1", s)  # убрать висящие запятые
    fixed = fixed[fixed.find("{"): fixed.rfind("}") + 1] if "{" in fixed else fixed
    try:
        return json.loads(fixed)
    except json.JSONDecodeError:
        log.warning("Не удалось разобрать заказ: %s", s[:300])
        return None


def _cut_hallucination(raw):
    """Оставляет только первую реплику: всё после выдуманного «Пользователь:» отбрасываем."""
    m = FAKE_TURN_RE.search(raw)
    if m:
        raw = raw[:m.start()]
    raw = SELF_LABEL_RE.sub("", raw)
    return raw.strip()


def _join_ru(items):
    items = [x for x in items if x]
    if len(items) <= 1:
        return "".join(items)
    return ", ".join(items[:-1]) + " и " + items[-1]


