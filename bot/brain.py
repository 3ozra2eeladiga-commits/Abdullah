    (r"с[ао]м[ао]в[ыи][вф][ао][зс]", "самовывоз"),
    (r"[ао]тк?р[ыи]тк", "открытк"),
    (r"др[уо]г[ии]е(?![а-яё])|др[уо]гии(?![а-яё])", "другие"),
