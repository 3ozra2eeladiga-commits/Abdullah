def _time_is_vague(t):
    """True, если время нечёткое («после обеда», «вечером»). ASAP и конкретный час — ок."""
    t = (t or "").strip().lower()
    if not t:
        return True
    if re.search(r"как можно скор|срочн|сейчас|асап|поскорее", t):
        return False
    if re.search(r"\d{1,2}[:.\s-]?\d{0,2}", t):  # есть цифры времени (14:00, к 14, 14-16)
        return False
    return True  # «после обеда», «вечером», «днём», «утром», «попозже» и т.п.


_MSK = datetime.timezone(datetime.timedelta(hours=3))


def _time_already_passed(date_s, time_s):
    """True, если заказ на СЕГОДНЯ и названный час уже прошёл (например, «сегодня в 06:00», а сейчас день)."""
    now = datetime.datetime.now(_MSK)
    d = (date_s or "").lower()
    is_today = ("сегодн" in d or now.strftime("%d.%m") in d
                or now.strftime("%d.%m.%Y") in d or now.strftime("%-d.%-m") in d)
    if not is_today:
        return False
    m = re.search(r"(\d{1,2})[:.\s-]?(\d{2})?", time_s or "")
    if not m:
        return False
    hh, mm = int(m.group(1)), int(m.group(2) or 0)
    if hh > 23 or mm > 59:
        return False
    return now.replace(hour=hh, minute=mm, second=0, microsecond=0) < now


# Части суток → час, после которого этот период СЕГОДНЯ уже считается прошедшим.
_PERIOD_PAST = [(r"ноч", 9), (r"утр|с утра", 11), (r"обед|дн[её]м|\bдень\b", 16), (r"вечер", 22)]


def _past_time_mention(text):
    """Клиент прямо назвал СЕГОДНЯШНЕЕ время, которое уже прошло («сегодня утром» вечером, «сегодня к 8» днём)."""
    t = (text or "").lower()
    if "сегодн" not in t or re.search(r"как можно скор|срочн|сейчас|поскорее|асап", t):
        return False
    now = datetime.datetime.now(_MSK)
    for m in re.finditer(r"(?:в|к|до|на)\s*(\d{1,2})(?:[:.\s-](\d{2}))?", t):   # конкретный час «сегодня в 8»
        hh, mm = int(m.group(1)), int(m.group(2) or 0)
        if hh <= 23 and mm <= 59 and now.replace(hour=hh, minute=mm, second=0, microsecond=0) < now:
            return True
    for pat, end_h in _PERIOD_PAST:   # часть суток («утром», «днём»)
        if re.search(pat, t) and now.hour >= end_h:
            return True
    return False


