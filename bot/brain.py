def _merge_roles(messages):
    """Склеивает подряд идущие сообщения одной роли — так требуют некоторые ИИ."""
    out = []
    for m in messages:
        if out and out[-1]["role"] == m["role"]:
            out[-1] = {"role": m["role"], "content": out[-1]["content"] + "\n\n" + m["content"]}
        else:
            out.append(dict(m))
    while out and out[0]["role"] != "user":
        out.pop(0)
    return out


def parse(raw, city=None):
    raw = _cut_hallucination(raw)
    reply = Reply()
    m = CITY_RE.search(raw)
    if m:
        reply.city = catalog.match_city(m.group(1)) or m.group(1).strip()
    city = reply.city or city
    city_cat = catalog.get_city(city)
    for m in PHOTO_RE.finditer(raw):
        item = catalog.get(m.group(1) or m.group(2), city)
        if item and item["images"] and item not in reply.photos and len(reply.photos) < 10:
            reply.photos.append(item)
    if not reply.photos and city_cat:
        # ИИ забыл метки — ищем в тексте названия товаров города и показываем их фото
        low = raw.lower()
        for item in city_cat.by_code.values():
            title = item["title"].lower()
            if len(title) >= 8 and title in low and item["images"] and len(reply.photos) < 10:
                reply.photos.append(item)
    m = ORDER_RE.search(raw)
    if m:
        reply.order_raw = m.group(1).strip()
        reply.order = _parse_order_json(reply.order_raw)
    else:
        # ИИ вывалил JSON заказа прямо в текст (без пары меток [ЗАКАЗ]…[/ЗАКАЗ]) — забираем его и прячем от клиента.
        span = _order_json_span(raw)
        if span:
            reply.order_raw = raw[span[0]:span[1]]
            reply.order = _parse_order_json(reply.order_raw)
            raw = raw[:span[0]] + raw[span[1]:]
    m = QUESTION_RE.search(raw)
    if m:
        reply.question = m.group(1).strip()
    reply.handoff = bool(HANDOFF_RE.search(raw))
    text = ORDER_RE.sub("", raw)
    text = re.sub(r"\[/?\s*ЗАКАЗ\s*\]", "", text)  # одиночная метка [ЗАКАЗ] без пары — не показываем клиенту
    text = QUESTION_RE.sub("", text)
    text = CITY_RE.sub("", text)
    text = PHOTO_RE.sub(lambda m: "" if catalog.get(m.group(1) or m.group(2), city) else m.group(0), text)
    text = HANDOFF_RE.sub("", text)
    text = FOREIGN_LINK_RE.sub("", text)  # чужие ссылки убираем, а ссылку на наш каталог оставляем
    text = re.sub(r"[ \t]+([,.!?])", r"\1", text)      # пробел перед знаком препинания
    text = re.sub(r"[,;]\s*$", "", text, flags=re.M)     # висящая запятая в конце строки
    text = re.sub(r"[ \t]{2,}", " ", text)
    text = re.sub(r"^[ \t]+", "", text, flags=re.M)
    text = re.sub(r"\n{3,}", "\n\n", text).strip()
    # Бот любит сыпать 🌸 в каждое предложение — оставляем максимум один на сообщение
    if text.count("🌸") > 1:
        first = text.index("🌸")
        text = text[:first + 1] + text[first + 1:].replace("🌸", "")
        text = re.sub(r"[ \t]{2,}", " ", text).strip()
    reply.text = text
    return reply


def respond(client, incoming, from_staff=False, quote=""):
    """Записывает входящее сообщение, спрашивает ИИ и возвращает разобранный ответ.

    quote — текст сообщения, на которое клиент ответил (reply): подпись фото букета и т.п. Используется
    ТОЛЬКО для распознавания (какой букет), но НЕ подмешивается в сам текст для ИИ, чтобы его не путать."""
    content = f"{STAFF_PREFIX} {incoming}" if from_staff else incoming

    # Для распознавания букета/города учитываем и цитату (на что ответил клиент).
    detect = f"{incoming}\n{quote}" if quote else incoming

    city = db.get_city(client)
    if not city and not from_staff:  # клиент мог сам назвать город или прийти по ссылке с сайта города
        city = catalog.match_city(incoming) or _city_from_url(detect)
        if city:
            db.set_city(client, city)

    # Букет, выбранный клиентом: по номеру (№600), ссылке с сайта или ответу (reply) на фото букета.
    picked = ((_picked_by_number(detect, city) + _picked_from_site(detect, city)
               + _picked_from_caption(detect, city)) if not from_staff else [])
    _seen = set()
    picked = [p for p in picked if not (p["code"] in _seen or _seen.add(p["code"]))]
    # Дополнения (открытка, шар, игрушка…) ДОБАВЛЯЮТ к заказу — выбранный букет при этом не меняется.
    addons = [p for p in picked if catalog.is_addon(p, city)]
    picked = [p for p in picked if p not in addons]
    if addons and not from_staff:
        saved = [c for c in (db.get_setting(f"addons:{client}") or "").split(",") if c]
        saved += [a["code"] for a in addons if a["code"] not in saved]
        db.set_setting(f"addons:{client}", ",".join(saved))
    # В историю пишем слова клиента; если он ответил (reply) на фото — дописываем, о каком товаре речь,
    # обычной фразой. Иначе ИИ видит только «вот это» и переспрашивает номер, хотя всё уже понятно.
    if quote and (picked or addons) and not from_staff:
        it0 = (picked or addons)[0]
        content = f"{incoming} — про «{it0['title']}» ({it0['price']} ₽)"
    db.add_message(client, "user", content)
    wants_photos = (not from_staff) and bool(SHOW_REQUEST_RE.search(incoming or ""))
    # Клиент хочет выбранный букет больше/меньше — не показываем другие, спрашиваем сумму.
    # Срабатывает и когда выбран букет (picked), и когда клиент пишет «этот/его/такой ... побольше» без reply.
    # НО не путаем с «покажи побольше ВАРИАНТОВ» — там как раз нужно показать.
    size_change = (bool(SIZE_CHANGE_RE.search(incoming or ""))
                   and not re.search(r"вариант|ещё|еще|друг|показ|покаж|выбор", incoming or "", re.I)
                   and (bool(picked) or bool(re.search(r"\bэтот\b|\bэту\b|\bэто\b|\bтакой\b|\bтакую\b|\bего\b|\bеё\b|\bее\b", incoming or "", re.I))))
    # «Сделать пышнее/скромнее» выбранный букет: запоминаем КАКОЙ букет и НА СКОЛЬКО добавить (доплата).
    # Флорист сам доберёт цветы на эту сумму. Других букетов не предлагаем.
    up_block, up_turn, up_target, up_amount, up_sign = "", False, None, "", "+"
    if not from_staff:
        up_key = f"upsize:{client}"
        if size_change:
            target = picked[0] if picked else _last_bouquet(db.history(client), city)
            if target:
                sign = "-" if re.search(r"меньше|поменьше|компактн|поскромн|дешевле", incoming or "", re.I) else "+"
                db.set_setting(up_key, f"{target['code']}|{sign}|")
        up = db.get_setting(up_key) or ""
        if up:
            code, up_sign, up_amount = (up.split("|") + ["", "", ""])[:3]
            up_target = catalog.get(code, city) or catalog.get(code)
            if up_target and not up_amount and not size_change:
                n = _money(incoming)
                if n:
                    up_amount = str(n)
                    db.set_setting(up_key, f"{code}|{up_sign}|{up_amount}")
                    up_turn = True
            if up_target:
                word = "ПЫШНЕЕ (добавить цветов)" if up_sign == "+" else "СКРОМНЕЕ (убрать часть цветов)"
                if not up_amount:
                    up_turn = True
                    up_block = (f"\n\n# КЛИЕНТ ХОЧЕТ СДЕЛАТЬ БУКЕТ «{up_target['title']}» ({up_target['price']} ₽) "
                                f"{word}\nСпроси ОДНИМ коротким вопросом, на какую сумму "
                                f"{'добавить' if up_sign == '+' else 'уменьшить'}, например: «На какую сумму добавить "
                                "цветов? Например, +3000 ₽». НЕ предлагай другие букеты, НЕ спрашивай коллег.")
                else:
                    total = up_target["price"] + (int(up_amount) if up_sign == "+" else -int(up_amount))
                    up_block = (f"\n\n# РЕШЕНО: букет «{up_target['title']}» собрать {word.lower()}, "
                                f"{'+' if up_sign == '+' else '−'}{up_amount} ₽ (итого за букет {total} ₽). Флорист сам "
                                "доберёт цветы на эту сумму.\nЕсли клиент только что назвал сумму — коротко подтверди и "
                                f"продолжай оформление (следующий недостающий вопрос). В [ЗАКАЗ] поставь этот букет "
                                f"(код {up_target['code']}) и \"доплата\": {'' if up_sign == '+' else '-'}{up_amount}. "
                                "НЕ предлагай другие букеты и НЕ задавай [ВОПРОС] коллегам.")
    addon_block = ""
    if addons:
        addon_block = ("\n\n# КЛИЕНТ ДОБАВЛЯЕТ К ЗАКАЗУ (это дополнение — выбранный букет НЕ меняется!)\n"
                       + "\n".join(f"- [{a['code']}] {a['title']} — {a['price']} ₽" for a in addons)
                       + "\nКоротко подтверди, добавь в «товары» [ЗАКАЗ] отдельной строкой с кодом. Если это открытка и "
                         "текст для неё ещё не известен — спроси текст. Продолжай оформление.")

    # Клиент назвал конкретный цветок (лилии, каллы...) — ищем его СТРОГО в каталоге, не даём ИИ выдумывать.
    flower_block, flower_photos, flower_absent = "", [], False
    flowers = _flowers_requested(incoming) if (not from_staff and city and not picked) else []
    if flowers:
        lines = []
        for canon, pat in flowers:
            pieces, bouquets = catalog.find_by_flower(pat, city)
            if pieces:
                flower_photos += pieces
                lines.append(f"{canon.upper()}: ЕСТЬ поштучно — " +
                             "; ".join(f"[{it['code']}] {it['title']} — {it['price']}₽" for it in pieces) +
                             ". Предлагай именно их.")
            elif bouquets:
                flower_photos += bouquets
                lines.append(f"{canon.upper()}: поштучно НЕТ, но есть БУКЕТЫ с ним — " +
                             "; ".join(f"[{it['code']}] {it['title']} — {it['price']}₽" for it in bouquets) +
                             f". Скажи, что отдельно (поштучно) {canon} нет, и предложи эти букеты с ним.")
            else:
                flower_absent = True
                lines.append(f"{canon.upper()}: сейчас НЕТ в каталоге (ни поштучно, ни в букетах). Честно скажи, "
                             f"что {canon} сейчас нет, и предложи популярные букеты из каталога или связь с флористом. "
                             f"НЕ придумывай {canon} и не называй цены на него.")
        flower_block = ("\n\n# КЛИЕНТ СПРАШИВАЕТ КОНКРЕТНЫЙ ЦВЕТОК — ДАННЫЕ ИЗ КАТАЛОГА (строго по ним!)\n"
                        "Предлагай ТОЛЬКО то, что указано ниже. Если цветка нет — так и скажи, альтернативы бери "
                        "из каталога. Ничего не выдумывай.\n" + "\n".join(lines))

    history = db.history(client)
    raw = llm.complete(system_prompt(history, city, picked, flower_block + up_block + addon_block, size_change),
                       _merge_roles(history))
    # ИИ выдал шаблонный отказ (ложный фильтр YandexGPT на безобидную просьбу) — не пугаем клиента, переспрашиваем.
    if llm.is_refusal(raw):
        if re.search(r"больше|крупнее|пышнее|объёмн|дороже|меньше|дешевле|бюджет", incoming or "", re.I):
            raw = "Конечно 🌸 На какую сумму ориентируетесь? Подберу вариант под неё."
        else:
            raw = "Секундочку 🌸 Уточните, пожалуйста, чуть подробнее — и я помогу подобрать."
    db.add_message(client, "assistant", raw)
    reply = parse(raw, city)
    if reply.city and reply.city in catalog.city_names and reply.city != city:
        db.set_city(client, reply.city)
        city = reply.city

    # В заказе берём настоящие название и цену товара из каталога по коду (чтобы ИИ не подменил, как «тюльпан»),
    # и добавляем то, что клиент уже выбрал (открытка, доплата за пышность), даже если ИИ это забыл.
    _fill_order(reply.order, city)
    keep_photos = False                          # фото выбора открытки — не трогать дальше
    if reply.order and not from_staff:
        _apply_client_state(reply.order, client, city)

    # Не даём оформить заказ без адреса (при доставке), телефонов, имён и открытки — вместо заказа просим недостающее.
    if reply.order:
        client_text = " ".join(m["content"] for m in history if m["role"] == "user")
        miss = _order_missing(reply.order, client_text)
        if miss:
            card_photos = []
            if miss == CARD_ASK_Q:
                miss = CARD_ASK_Q.format(min=min((c["price"] for c in catalog.cards(city)), default=50))
            elif miss == CARD_PICK_Q:
                card_photos = catalog.cards(city)
                miss = CARD_PICK_Q.format(text=str(reply.order.get("открытка") or "").strip())
            reply.order = None
            reply.order_raw = ""
            reply.photos = card_photos
            reply.text = miss
            keep_photos = bool(card_photos)
    # Метка [ЗАКАЗ] не разобралась в JSON (ИИ поставил её рано/криво) — флористу неполный заказ НЕ шлём.
    if reply.order_raw and not reply.order:
        reply.order_raw = ""

    # Заказ флористу уходит ТОЛЬКО после «да» на итог, который клиент видел. Итог «всё верно?» собирает КОД
    # (аккуратно, без служебных данных, с правильной доставкой), а не ИИ.
    order_text = False                           # текст ответа — итог/принятие заказа (фото не нужны)
    if not from_staff:
        confirmed = bool(CONFIRM_YES_RE.search(incoming or "")) and not CORRECTION_RE.search(incoming or "")
        prev = db.get_pending_order(client)      # итог, который клиент уже видел
        if reply.order:                          # ИИ собрал полный заказ
            if confirmed and prev:
                pass                             # клиент сказал «да» на итог — отправляем (свежие данные)
            else:
                db.set_pending_order(client, reply.order)
                reply.text = _order_summary(reply.order)
                reply.photos, reply.order, reply.order_raw = [], None, ""
                order_text = True
        elif confirmed:
            pend = prev
            # Запасной путь: итог был, но ИИ не поставил метку — соберём заказ из переписки.
            if not pend and re.search(r"принят|оформл|свяжут|готов|подтвержд|заказ ваш", reply.text or "", re.I):
                pend = _extract_order(client, city)
                if pend:
                    _apply_client_state(pend, client, city)
            if pend:
                reply.order = pend
        if reply.order:                          # уходит флористу
            db.clear_pending_order(client)
            _clear_client_state(client)
            reply.text = "Спасибо! Заказ принят 🌸 Скоро с вами свяжутся по оплате."
            reply.photos = []
            order_text = True

    # «Вопрос флористу», который на самом деле про подбор букетов — не беспокоим коллег, показываем сами.
    force_options = False
    if reply.question and FAKE_QUESTION_RE.search(reply.question):
        reply.question = ""
        force_options = True

    # Клиент выбрал букет (по фото/номеру) — показываем ТОЛЬКО его, без «других вариантов». Он уже выбрал,
    # как чипсы в магазине: не предлагаем альтернативы, а идём оформлять.
    if picked and not reply.order and not size_change and not order_text and not keep_photos:
        reply.photos = list(picked)
    elif size_change:
        reply.photos = []

    # Клиент спросил конкретный цветок — показываем СТРОГО найденное в каталоге (а не что выдумал ИИ).
    if flowers and not reply.order:
        if flower_photos:
            seen = set()
            reply.photos = [x for x in flower_photos if not (x["code"] in seen or seen.add(x["code"]))][:MIN_OPTIONS]
        elif flower_absent:   # цветка нет — показываем популярные букеты как альтернативу
            cc = catalog.get_city(city)
            reply.photos = cc.relevant_items("популярные букеты", limit=3, bouquets_only=True)[:3] if cc else []

    # Перечисление вариантов с ценами (3+ «₽») — это показ букетов, а НЕ этап оформления,
    # даже если в тексте есть слово «оформлю» (из подсказки про номер/ссылку). Иначе фото пропадали.
    is_variant_listing = (reply.text or "").count("₽") >= 3
    is_order_step = bool(ORDER_STEP_RE.search(reply.text or "")) and not is_variant_listing
    if reply.photos and is_order_step and not picked and not keep_photos:
        reply.photos = []

    # Если бот перечислил товары с ценами (есть «₽») и это не этап заказа — это показ вариантов.
    # Тогда код сам прикладывает фото (минимум 5), даже если модель забыла метки [ФОТО] или прислала только текст.
    offering = (("₽" in (reply.text or "")) or force_options or wants_photos) \
        and not is_order_step and not picked and not size_change and not order_text and not up_turn \
        and not keep_photos
    city_cat = catalog.get_city(city)
    # Для режима «конкретный цветок» и «сделать больше/меньше» общий добор фото не нужен.
    if city_cat and (len(reply.photos) >= 2 or offering) and len(reply.photos) < MIN_OPTIONS \
            and not flowers and not size_change and not order_text and not up_turn and not keep_photos:
        query = " ".join([m["content"] for m in history if m["role"] == "user"][-4:])
        # Добираем ТОЛЬКО букеты (не поштучные розы по 250₽, не открытки с котиками), кроме случая,
        # когда клиент ПРЯМО СЕЙЧАС просит именно поштучно/подарки. Смотрим текущее сообщение, а не всю историю,
        # чтобы слово «открытка» из этапа сбора данных не превращало показ букетов в показ открыток.
        bouquets_only = not re.search(
            r"поштучн|штучн|\bшт\b|\d+\s*(?:роз|тюльпан|гвоздик|хризантем|гербер|пион|ромаш)|"
            r"шар|игрушк|подар|открытк|ваз|растен|горшк|сухоцвет|невест|"
            r"похорон|траур|помин|соболезн|венок|гвоздик", incoming or "", re.I)
        shown = {p["code"] for p in reply.photos}
        for it in city_cat.relevant_items(query, shown, limit=MIN_OPTIONS * 2, bouquets_only=bouquets_only):
            if it["code"] not in shown:
                reply.photos.append(it)
                shown.add(it["code"])
                if len(reply.photos) >= MIN_OPTIONS:
                    break
    # Показ вариантов — максимум 5 фото за раз, чтобы не заваливать клиента.
    if offering and len(reply.photos) > MIN_OPTIONS:
        reply.photos = reply.photos[:MIN_OPTIONS]

    # Если перехватили «вопрос о подборе» и сами приложили фото — заменяем «уточню…» на нормальный показ.
    if force_options and reply.photos and re.search(r"уточн|секунд|минут|подожд", reply.text or "", re.I):
        reply.text = "Вот что могу предложить 🌹 Какой вариант нравится?"

    # Букет уже выбран (по фото/номеру/ссылке), а ИИ всё равно переспрашивает «какой букет / номер» —
    # не даём ему это сделать: подтверждаем выбор и идём к оформлению.
    if picked and not size_change and not from_staff and ASK_WHICH_RE.search(reply.text or ""):
        it = picked[0]
        nxt = ("Подскажите, пожалуйста, в какой город нужны цветы?" if not city else
               "Подскажите, пожалуйста: доставка или самовывоз, и на какую дату и к какому часу?")
        reply.text = f"Отличный выбор 🌸 {it['title']} — {it['price']} ₽. Оформляем его! {nxt}"
        reply.photos = []

    # Режим «пышнее/скромнее»: никаких других букетов и вопросов коллегам — флорист получит доплату в заказе.
    if up_target and not from_staff:
        if up_turn and not keep_photos and not order_text:
            reply.photos = []
        if reply.question and re.search(r"увелич|пышн|добав|больш|объ[её]м|уменьш|сумм", reply.question, re.I):
            reply.question = ""
        if up_turn and up_amount and re.search(r"уточн\w*[^.?!]{0,30}флорист", reply.text or "", re.I):
            total = up_target["price"] + (int(up_amount) if up_sign == "+" else -int(up_amount))
            reply.text = (f"Хорошо 🌸 {'Добавим цветов' if up_sign == '+' else 'Соберём скромнее'} — "
                          f"{'+' if up_sign == '+' else '−'}{_rub(int(up_amount))}, итого за букет {_rub(total)}. "
                          "Флорист соберёт его по этой сумме. Продолжим оформление?")

    # ИИ написал заглушку «[ссылка на каталог]» вместо настоящего адреса — подставляем реальный URL города.
    if reply.text and LINK_PLACEHOLDER_RE.search(reply.text):
        site = config.cities().get(city, "")
        reply.text = LINK_PLACEHOLDER_RE.sub(site, reply.text) if site else LINK_PLACEHOLDER_RE.sub("", reply.text)

    # Клиент назвал СЕГОДНЯШНЕЕ время, которое уже прошло («сегодня утром» вечером) — сразу честно уточняем.
    if not from_staff and _past_time_mention(incoming):
        reply.text = ("Это время сегодня, к сожалению, уже прошло 🙏 Подскажите, пожалуйста, на какое время "
                      "сегодня (попозже) или на другую дату — и я всё подберу.")
        reply.photos, reply.order, reply.order_raw, reply.question, reply.handoff = [], None, "", "", False
    return reply
